// Runs every bench and writes a report.
//
//   node --no-warnings --import ./bench/lib/register.mjs bench/run.mjs
//   pwsh -File bench/bench.ps1

import { mkdir, writeFile } from "node:fs/promises";

import { runRender, TARGETS, SCALES } from "./benches/render.mjs";
import { runTimers, timerTotals } from "./benches/timers.mjs";
import { runLayout } from "./benches/layout.mjs";

const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const resultsDir = new URL("./results/", import.meta.url);
await mkdir(resultsDir, { recursive: true });

const say = (line = "") => console.log(line);
const table = (head, rows) => {
  const widths = head.map((h, i) => Math.max(h.length, ...rows.map((r) => String(r[i] ?? "").length)));
  const line = (cells) => cells.map((c, i) => String(c ?? "").padEnd(widths[i])).join("  ").trimEnd();
  return [line(head), widths.map((w) => "-".repeat(w)).join("  "), ...rows.map(line)];
};

say("render bench (real mod code, stubbed app)\n");
const renderStart = Date.now();
const render = await runRender({ log: () => {} });
say(`  ${render.length} renders in ${((Date.now() - renderStart) / 1000).toFixed(1)}s, ${render.filter((r) => r.error).length} failed`);

const renderRows = [];
for (const target of [...new Set(render.map((r) => r.target))]) {
  const own = render.filter((r) => r.target === target);
  const cells = [target];
  for (const scale of SCALES) {
    const row = own.find((r) => r.scale === scale.name);
    cells.push(row && !row.error ? `${row.renderMs.toFixed(3)} ms / ${Math.round(row.elements)} el` : `failed: ${row?.error ?? "?"}`);
  }
  renderRows.push(cells);
}

say("\ntimer budget (static scan)\n");
const timers = await runTimers();
const totals = timerTotals(timers);
const timerRows = totals.map((t) => [t.mod, t.timers, t.shownPerMinute, t.hiddenPerMinute, t.withWork]);
const detailRows = timers
  .sort((a, b) => (a.mod + a.file).localeCompare(b.mod + b.file) || a.line - b.line)
  .map((r) => [`${r.mod}/${r.file}:${r.line}`, `${r.ms} ms`, r.kind, r.gated ? "yes" : "NO", r.calls.join(",") || "-"]);

say("\nlayouts\n");
const layouts = await runLayout();
const layoutRows = layouts.map((l) => l.error ? [l.layout, "ERROR", l.error] : [l.layout, l.nodes, l.liveCopies, l.hidden, l.copies]);

const sections = [
  `# Mod performance report — ${new Date().toISOString().slice(0, 16).replace("T", " ")}`,
  "",
  "Generated by `bench/run.mjs`. Numbers are from this machine and this run;",
  "compare rows within a table, not across runs.",
  "",
  "## Render cost",
  "",
  "Element build + data prep for one render, median of 40. The app lays out and",
  "paints that tree afterwards, in Rust: that half is not measured here and grows",
  "with the element count.",
  "",
  ...table(["target", ...SCALES.map((s) => s.name)], renderRows).map((l) => `    ${l}`),
  "",
  "## Timer budget per minute",
  "",
  "Static scan of the registrations. `hidden` is what still runs while the window",
  "is not presenting, after the early returns.",
  "",
  ...table(["mod", "timers", "shown/min", "hidden/min", "unguarded with work"], timerRows).map((l) => `    ${l}`),
  "",
  "### Every timer",
  "",
  ...table(["where", "period", "kind", "guarded", "work"], detailRows).map((l) => `    ${l}`),
  "",
  "## Layouts",
  "",
  "Every mod block is a live copy: its timers, its data, its renders.",
  "",
  ...table(["layout", "nodes", "mod copies", "hidden", "copies"], layoutRows).map((l) => `    ${l}`),
  "",
  `Targets: ${TARGETS.length}, scales: ${SCALES.map((s) => s.name).join(", ")}.`,
];

for (const line of sections) say(line);

const file = new URL(`./${stamp}.md`, resultsDir);
await writeFile(file, sections.join("\n") + "\n");
say(`\nwritten: bench/results/${stamp}.md`);
